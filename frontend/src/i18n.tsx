const Ctx = createContext<{ lang: Lang; t: (s: string) => string; setLang: (l: Lang) => void }>({ lang: "sl", t: (s) => s, setLang: () => {} });

export function I18n({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem("potok.lang");
      if (saved === "sl" || saved === "en") return saved;
    } catch { /* ignore */ }
    return navigator.language.startsWith("sl") ? "sl" : "en";
  });
  const setLang = (l: Lang) => { setLangState(l); try { localStorage.setItem("potok.lang", l); } catch { /* ignore */ } };
  const t = (s: string) => (lang === "sl" ? sl[s] ?? s : s);
  return <Ctx.Provider value={{ lang, t, setLang }}>{children}</Ctx.Provider>;
}

export const useT = () => useContext(Ctx);
